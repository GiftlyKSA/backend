def language(request: Request) -> str:
    """Return the selected language, defaulting to Arabic."""
    selected = request.cookies.get(LANGUAGE_COOKIE, "ar")
    return selected if selected in LANGUAGES else "ar"


def theme(request: Request) -> str:
    """Return a valid dashboard color theme."""
    selected = request.cookies.get(THEME_COOKIE, "light")
    return selected if selected in THEMES else "light"


def translate(value: object, selected_language: str) -> str:
    """Translate a visible label while leaving unknown values unchanged."""
    label = str(value)
    if selected_language != "ar":
        return label
    normalized = label.replace("_", " ").title() if label.isupper() else label
    return ARABIC.get(label, ARABIC.get(normalized, label))


def template_context(request: Request) -> dict[str, object]:
    """Expose the chosen display preferences and translation helper to Jinja."""
    selected_language = language(request)
    return {
        "utc_datetime": utc_datetime,
        "admin_datetime": admin_datetime,
        "stylesheet_url": STYLESHEET_URL,
        "theme_script_url": THEME_SCRIPT_URL,
        "datetime_script_url": DATETIME_SCRIPT_URL,
        "lang": selected_language,
        "theme": theme(request),
        "tr": lambda value: translate(value, selected_language),
    }


def utc_datetime(value: datetime) -> str:
    """Display an audit instant with an explicit UTC label."""
    aware = value.replace(tzinfo=UTC) if value.tzinfo is None else value
    return aware.astimezone(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
